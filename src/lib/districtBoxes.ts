/** Districts whose box overlaps the map's view. */
export function districtsInView(bounds: { north: number; south: number; east: number; west: number }): string[] {
  return DISTRICT_BOXES
    .filter(([, w, s, e, n]) => w <= bounds.east && e >= bounds.west && s <= bounds.north && n >= bounds.south)
    .map(([code]) => code)
}
